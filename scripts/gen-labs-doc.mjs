// Generates docs/LABS.md from the in-app lab guides and component reference,
// and fails if any guide is missing or points at an unknown task, component or lab.
// Usage: npm run docs
import { writeFileSync } from 'node:fs';
import { MODULES } from '../src/data/curriculum.js';
import { CANVAS_GUIDE, GUIDES } from '../src/data/guides.js';
import { MISSIONS } from '../src/data/missions.js';
import { TASK_BY_ID } from '../src/data/progression.js';
import { CATEGORIES, REFERENCE, REF_BY_ID } from '../src/data/reference.js';

const errors = [];
const labIds = MODULES.flatMap((m) => m.labs.map((l) => l.id));
for (const id of labIds) if (!GUIDES[id]) errors.push(`lab "${id}" has no guide`);
for (const [id, g] of Object.entries(GUIDES)) {
  if (!labIds.includes(id)) errors.push(`guide "${id}" is not a lab`);
  for (const k of ['objective', 'steps', 'expected', 'hints', 'solution', 'refs', 'tasks']) if (!g[k]) errors.push(`guide "${id}" is missing ${k}`);
  for (const r of g.refs || []) if (!REF_BY_ID[r]) errors.push(`guide "${id}" refs unknown component "${r}"`);
  for (const t of g.tasks || []) if (!TASK_BY_ID[t]) errors.push(`guide "${id}" lists unknown task "${t}"`);
}
for (const r of REFERENCE) for (const l of r.labs || []) if (!labIds.includes(l)) errors.push(`component "${r.id}" lists unknown lab "${l}"`);
const labTasks = new Set(Object.values(GUIDES).flatMap((g) => g.tasks));
for (const t of Object.values(TASK_BY_ID)) if (t.kind === 'lab' && !labTasks.has(t.id)) errors.push(`lab task "${t.id}" is not covered by any guide`);
if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

const out = [];
const p = (s = '') => out.push(s);
p('# XC Flow Academy · Lab Guide & Component Reference');
p();
p('<!-- Generated by `npm run docs` from src/data/guides.js and src/data/reference.js. Do not edit by hand. -->');
p();
p('This guide explains how to run every lab in the simulator and what each F5 Distributed Cloud component does. The same content is built into the app: each lab has a **How to run this lab** panel above the console, and the **Component Reference** button in the header opens a searchable glossary.');
p();
p('## How the workbench works');
p();
p('Every module screen is split in two. On the left is the live architecture diagram with an inspector card; on the right is the simulated XC Console with one tab per lab.');
p();
p('1. Pick a module in the skill tree, then a lab tab above the console.');
p('2. Read the lab guide panel: objective, steps and what success looks like.');
p('3. Do the steps in the console. Wrong choices are explained inline, so experimenting is safe.');
p('4. Stuck? Open **Hints**, and only then **Reveal solution**.');
p('5. Watch the diagram react: sites come online, tunnels turn green, attacks die at the RE.');
p();
p('XP is awarded once per objective, so you can replay any lab. Labs that depend on earlier work (for example, a site being online) offer a **Fast-track (no XP)** button.');
p();
p('### Using the diagram');
p();
p(CANVAS_GUIDE.intro);
p();
p('| Control | What it shows |');
p('| --- | --- |');
for (const [k, v] of CANVAS_GUIDE.controls) p(`| ${k} | ${v} |`);
p();
p('## Contents');
p();
for (const m of MODULES) p(`- [Module ${m.num}: ${m.title}](#module-${m.num})`);
p('- [Missions](#missions)');
p('- [Component reference](#component-reference)');
p();

for (const m of MODULES) {
  p(`<a id="module-${m.num}"></a>`);
  p(`## Module ${m.num}: ${m.title}`);
  p();
  p(m.summary);
  p();
  const canvas = CANVAS_GUIDE.byModule[m.id] || [];
  if (canvas.length) {
    p('**Canvas exercises**');
    p();
    for (const c of canvas) p(`- **${TASK_BY_ID[c.task].label}** (+${TASK_BY_ID[c.task].xp} XP): ${c.how}`);
    p();
  }
  m.labs.forEach((lab, i) => {
    const g = GUIDES[lab.id];
    p(`### ${m.num}.${i + 1} ${lab.label}`);
    p();
    p(`**Objective:** ${g.objective}`);
    p();
    if (g.before) {
      p(`> **Before you start:** ${g.before}`);
      p();
    }
    p('**Steps**');
    p();
    g.steps.forEach((s, j) => p(`${j + 1}. ${s}`));
    p();
    p(`**Success looks like:** ${g.expected}`);
    p();
    p('**XP objectives:** ' + g.tasks.map((t) => `${TASK_BY_ID[t].label} (+${TASK_BY_ID[t].xp})`).join(' · '));
    p();
    p('**Hints**');
    p();
    for (const h of g.hints) p(`- ${h}`);
    p();
    p('<details><summary>Solution</summary>');
    p();
    for (const s of g.solution) p(`- ${s}`);
    p();
    p('</details>');
    p();
    p('**Components used:** ' + g.refs.map((r) => `[${REF_BY_ID[r].name}](#ref-${r})`).join(', '));
    p();
  });
}

p('<a id="missions"></a>');
p('## Missions');
p();
p('Missions are timed scenarios that chain several labs. Start one from the skill tree; objectives tick off as the matching lab events happen. Follow the lab guides above for each step.');
p();
for (const ms of MISSIONS) {
  p(`### Mission ${ms.num}: ${ms.title}`);
  p();
  p(ms.brief);
  p();
  p('Labs used: ' + ms.labs.map((l) => MODULES.flatMap((m) => m.labs).find((x) => x.id === l)?.label || l).join(', '));
  p();
  for (const o of ms.objectives) p(`- [ ] ${o.label}`);
  p();
}

p('<a id="component-reference"></a>');
p('## Component reference');
p();
for (const c of CATEGORIES) {
  p(`### ${c.label}`);
  p();
  for (const r of REFERENCE.filter((x) => x.category === c.id)) {
    p(`<a id="ref-${r.id}"></a>`);
    p(`#### ${r.name}`);
    p();
    p(`*${r.short}*`);
    p();
    p(r.what);
    p();
    p('What it does:');
    p();
    for (const d of r.does) p(`- ${d}`);
    p();
    if (r.analogy) {
      p(`Think of it as: ${r.analogy}`);
      p();
    }
    if (r.where) {
      p(`Where you configure it: ${r.where}`);
      p();
    }
    const labs = (r.labs || []).map((l) => MODULES.flatMap((m) => m.labs).find((x) => x.id === l)?.label).filter(Boolean);
    if (labs.length) {
      p(`Practise it in: ${labs.join(', ')}`);
      p();
    }
  }
}
p('---');
p();
p('Educational simulator. Not affiliated with or endorsed by F5, Inc. Console screens, IPs and metrics are illustrative.');

writeFileSync(new URL('../docs/LABS.md', import.meta.url), out.join('\n') + '\n');
console.log(`docs/LABS.md written: ${labIds.length} labs, ${REFERENCE.length} components`);
